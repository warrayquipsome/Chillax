#!/usr/bin/env python3
"""BTcord CSS health check.

Run after Discord updates (or before a release):

    python3 scripts/check-css.py

Checks every .css file in the repo for:
  1. CSS syntax errors                          (via tinycss2 if installed)
  2. Unbalanced braces                          (fallback when tinycss2 is absent)
  3. Pre-2023 Discord class hashes              (e.g. .userPopout-2j1gM4 -- those
     element names were removed when Discord rebuilt its client, so any rule
     still targeting them is dead weight that can be deleted or rewritten)
  4. Stale upstream @import URLs                (warrayquipsome.github.io must
     not come back -- BTcord loads from bt-studio-dev.github.io/BTcord)
  5. Pre-Visual-Refresh variables used WITHOUT a fallback
     (Discord dropped these in the Visual Refresh; they only still work in
     BTcord because btcord.theme.css aliases them, so prefer the new names:
     --text-default, --text-strong, --background-base-*, --control-secondary-*)

Exit code is 1 only for syntax errors; checks 3-5 are warnings worth a look.
UserArea.css is exempt from check 3: it intentionally styles the
BetterDiscord SpotifyControls plugin, whose DOM uses legacy-style classes.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# A legacy class looks like `.someName-1A2b3C` (dash + 5-7 mixed-case chars).
# Modern Discord uses `.someName_abc123` or `_<hex>-someName` instead.
CLASS_RE = re.compile(r'\.(-?[A-Za-z_][A-Za-z0-9_-]*)')
LEGACY_ALLOW = {
    'theme-dark', 'theme-light', 'theme-darker', 'theme-midnight',
    'visual-refresh', 'stop-animations', 'custom-user-profile-theme',
    'user-profile-modal', 'user-profile-popout', 'user-profile-sidebar',
    'floating-window', 'floating-window-titlebar', 'floating-window-content',
    'public-DraftEditorPlaceholder-root', 'public-DraftEditor-content',
    'spinner-item', 'btn-primary', 'banner-danger', 'markdown-hover',
}
LEGACY_EXEMPT_FILES = {'UserArea.css'}  # BD SpotifyControls plugin DOM

STALE_VARS = {
    '--text-normal': '--text-default',
    '--header-primary': '--text-strong',
    '--header-secondary': '--text-subtle',
    '--background-primary': '--background-base-low',
    '--background-secondary': '--background-base-lower',
    '--background-tertiary': '--background-base-lowest',
    '--background-floating': '--background-surface-highest',
    '--brand-experiment': '--brand-500',
    '--channels-default': '--interactive-text-default / --channel-icon',
    '--button-secondary-background': '--control-secondary-background-default',
}


def syntax_check(path, text):
    """Return list of error strings (empty = OK)."""
    try:
        import tinycss2

        rules = tinycss2.parse_stylesheet(text, skip_comments=False, skip_whitespace=False)
        errors = []

        def walk(nodes):
            for node in nodes or []:
                if getattr(node, 'type', None) == 'error':
                    errors.append(f'line {node.source_line}: {node.message}')
                for attr in ('content', 'prelude'):
                    child = getattr(node, attr, None)
                    if isinstance(child, list):
                        walk(child)

        walk(rules)
        return errors
    except ImportError:
        depth = 0
        for i, ch in enumerate(text):
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
                if depth < 0:
                    return [f'unbalanced closing brace near char {i}']
        return [] if depth == 0 else [f'unbalanced braces (depth {depth})']


def main():
    files = sorted(ROOT.rglob('*.css'))
    errors_total = warnings_total = 0

    for f in files:
        rel = f.relative_to(ROOT)
        text = f.read_text(errors='ignore')
        problems = []

        for e in syntax_check(f, text):
            problems.append(f'SYNTAX ERROR: {e}')
            errors_total += 1

        if f.name == 'btcord.bundle.theme.css':
            # Generated by scripts/build-bundle.py from the checked sources:
            # syntax only (legacy/var checks run against the source files).
            ok = not problems
            print(f"[{'ok  ' if ok else 'FAIL'}] {rel} ({len(text.splitlines())} lines, generated)")
            for pr in problems:
                print(f'       {pr}')
            continue

        if 'warrayquipsome.github.io/Chillax' in text:
            problems.append('WARNING: stale upstream import URL (should be bt-studio-dev.github.io/BTcord)')
            warnings_total += 1

        # strip comments before selector/variable scanning
        code = re.sub(r'/\*.*?\*/', '', text, flags=re.S)

        if f.name not in LEGACY_EXEMPT_FILES:
            def is_legacy(name):
                # Legacy hashes are exactly `name-Hash12` (one dash, 5-7 char
                # suffix containing a digit or uppercase letter). This excludes
                # semantic classes (.editor-wrapper), multi-dash classes
                # (.user-profile-modal) and the modern hash-first format
                # (.c322aadb96ff59c9-search).
                parts = name.split('-')
                if len(parts) != 2:
                    return False
                prefix, suffix = parts
                if len(prefix) >= 12 and all(c in 'abcdef0123456789_' for c in prefix.lower()):
                    return False
                if not (5 <= len(suffix) <= 7):
                    return False
                if suffix.isalpha() and suffix.islower():
                    return False
                return any(c.isdigit() or c.isupper() for c in suffix)

            legacy = {
                m.group(1)
                for m in CLASS_RE.finditer(code)
                if is_legacy(m.group(1))
                and m.group(1) not in LEGACY_ALLOW
                and not any(m.group(1).startswith(p) for p in ('bd-', 'vc-', 'channelTabs-'))
            }
            for name in sorted(legacy):
                problems.append(f'WARNING: likely-dead pre-2023 class `.{name}`')
                warnings_total += 1

        for old, new in STALE_VARS.items():
            if f.name == 'btcord.theme.css':
                continue  # this file *defines* the old-name aliases on purpose
            # Ignore the inner var(--old) of an intentional nested fallback
            # like var(--text-strong, var(--header-primary)).
            scrubbed = re.sub(r',\s*var\(\s*' + re.escape(old) + r'\s*\)', '', code)
            hits = len(re.findall(r'var\(\s*' + re.escape(old) + r'\s*\)', scrubbed))
            if hits:
                problems.append(f'WARNING: {hits}x var({old}) without fallback (prefer {new})')
                warnings_total += 1

        status = 'FAIL' if any(p.startswith('SYNTAX') for p in problems) else ('warn' if problems else 'ok  ')
        print(f'[{status}] {rel} ({len(text.splitlines())} lines)')
        for p in problems[:12]:
            print(f'       {p}')
        if len(problems) > 12:
            print(f'       ... and {len(problems) - 12} more')

    print(f'\n{len(files)} files, {errors_total} syntax error(s), {warnings_total} warning(s)')
    sys.exit(1 if errors_total else 0)


if __name__ == '__main__':
    main()
